/**
 * 联机征召「本席已交卷、正在等别席挑完」这一段的共用口径（2026-11-13 用户口令逐字）。
 *
 * 用户原话＝「征召页面不要变化，只要下方的征召按钮换成一句『正在等待其他玩家完成征召』」。
 * 房主屏（`GeneralDraft`）与客人屏（`GuestDraftStage`）都用这一句、这一把判据，
 * 免得一边写着"在等别人"、另一边还写着"已经完成了"或"这一席是别人的"。
 *
 * 这一层不读 store、不读线上帧、不 import React：只放常量与一个纯判据，两端各自缓存画面。
 */

export const WAITING_FOR_OTHERS_TEXT = '正在等待其他玩家完成征召';

/**
 * 纯判据：**自己这一席此前有过一份属于自己的名单**（`hasOwnList`）
 * 且**现在被"不是我这一席"挡住**（`blocked`）⇒ 正在等别人挑完。
 *
 * 为什么需要 `hasOwnList`：房主发来的"还没轮到你这一席"与"你这一席已经完成了"
 * 在帧上长得一模一样（都是空名单＋一句人话），唯一能把两者分开的，
 * 就是这一席此前有没有真的收到过名单。从没轮到过自己时不许冒充"已完成在等别人"，
 * 那一屏仍照房主原话写"还没轮到你这一席"。
 *
 * `blocked` 的两端取法不同，含义相同：
 *  - 客人屏＝收到空名单帧（房主不再给这一席发候选）；
 *  - 房主屏＝席位闸判出"现在挑将的那一席不是我这台"（`seatLocked`）。
 */
export function isWaitingForOthers(hasOwnList: boolean, blocked: boolean): boolean {
  return hasOwnList && blocked;
}
